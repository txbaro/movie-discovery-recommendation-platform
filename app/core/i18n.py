def get_locale(request: Request) -> str:
    locale = request.cookies.get("locale", DEFAULT_LOCALE).lower()
    return locale if locale in SUPPORTED_LOCALES else DEFAULT_LOCALE


def translate(locale: str, key: str, **values) -> str:
    text = TRANSLATIONS.get(locale, TRANSLATIONS[DEFAULT_LOCALE]).get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LOCALE].get(key, key)
    try:
        return text.format(**values)
    except (KeyError, ValueError):
        return text


def translate_genres(locale: str, genres: tuple[str, ...]) -> list[str]:
    if locale != "en":
        return list(genres)
    return [ENGLISH_GENRE_LABELS.get(genre, genre) for genre in genres]


def template_i18n_context(request: Request) -> dict[str, object]:
    locale = get_locale(request)

    def translator(key: str, **values) -> str:
        return translate(locale, key, **values)

    return {
        "locale": locale,
        "t": translator,
        "weekday": lambda day: WEEKDAY_LABELS[locale][day.weekday()],
    }
